func TestBenchPayloadsAreRealistic(t *testing.T) {
	var res apiResponse
	if err := json.Unmarshal(repairInvalidEscapes(benchFeedsPayload), &res); err != nil {
		t.Fatalf("decode feeds payload: %v", err)
	}
	var feeds []apiFeedItem
	if err := json.Unmarshal(res.Content, &feeds); err != nil {
		t.Fatalf("decode feeds content: %v", err)
	}
	if len(feeds) < 20 {
		t.Fatalf("want at least 20 feeds, got %d", len(feeds))
	}
	for _, f := range feeds {
		if f.ID == "" || f.CreateTime == "" {
			t.Fatalf("incomplete feed row: %+v", f)
		}
	}
	if !bytes.Contains(benchFeedsPayload, []byte(`\'`)) {
		t.Fatal("feeds payload lost its invalid escapes; regenerate")
	}
	if len(benchSContent) < 10000 {
		t.Fatalf("scontent sample too small: %d bytes", len(benchSContent))
	}
	if !bytes.Contains([]byte(benchSContent), []byte("<p>")) ||
		!bytes.Contains([]byte(benchSContent), []byte("&")) {
		t.Fatal("scontent sample lost its tags/entities; regenerate")
	}
}
