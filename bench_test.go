func gunzipB64(s string) []byte {
	gz, err := gzip.NewReader(base64.NewDecoder(base64.StdEncoding, strings.NewReader(s)))
	if err != nil {
		panic(err)
	}
	b, err := io.ReadAll(gz)
	if err != nil {
		panic(err)
	}
	return b
}

